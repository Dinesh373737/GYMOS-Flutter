// One-time setup for running GymOS on a new computer.
//
//   dart tool/setup.dart                 # asks for the optional API keys
//   dart tool/setup.dart --no-prompt     # keys from GROQ_API_KEY / ALLEVENTS_API_KEY env vars
//   dart tool/setup.dart --skip-web      # skip building the web app
//
// It creates gymos2/gymos2_server/config/passwords.yaml with fresh local
// secrets (never committed), fetches packages, and builds the web app that the
// server hosts. Only the Flutter SDK is required (it includes Dart).
import 'dart:io';
import 'dart:math';

final _root = Directory.fromUri(Platform.script.resolve('..'));
final _workspace = Directory('${_root.path}gymos2');
final _server = Directory('${_workspace.path}/gymos2_server');
final _app = Directory('${_workspace.path}/gymos2_flutter');
final _passwords = File('${_server.path}/config/passwords.yaml');

Future<void> main(List<String> args) async {
  if (!_server.existsSync() || !_app.existsSync()) {
    _fail('Run this from a GymOS checkout (gymos2/ was not found).');
  }
  final prompt = !args.contains('--no-prompt') && stdin.hasTerminal;

  _step('1/3', 'Local secrets');
  if (_passwords.existsSync()) {
    stdout.writeln(
      '  ${_rel(_passwords)} already exists; keeping it. Edit it to change '
      'API keys.',
    );
  } else {
    final groq = _key(
      'GROQ_API_KEY',
      'Groq API key for the AI coach (free at https://console.groq.com/keys)',
      prompt,
    );
    final events = _key(
      'ALLEVENTS_API_KEY',
      'Parse.bot key for London/New York/Tokyo event listings (optional)',
      prompt,
    );
    _passwords.writeAsStringSync(_passwordsYaml(groq, events));
    stdout.writeln('  Created ${_rel(_passwords)} (git ignores this file).');
    if (groq == null) {
      stdout.writeln(
        '  No Groq key: everything works except the "Ask GymOS" coach.',
      );
    }
  }

  _step('2/3', 'Packages');
  await _run('flutter', ['pub', 'get'], _workspace);

  if (args.contains('--skip-web')) {
    _step('3/3', 'Web app (skipped)');
  } else {
    _step('3/3', 'Web app (takes a few minutes the first time)');
    await _run('flutter', ['build', 'web', '--release'], _app);
    final target = Directory('${_server.path}/web/app');
    if (target.existsSync()) target.deleteSync(recursive: true);
    _copy(Directory('${_app.path}/build/web'), target);
    stdout.writeln('  Copied the web build to ${_rel(target)}.');
  }

  final ips = await _lanAddresses();
  stdout.writeln('''

Setup complete.

Start the server (keep it running while you use GymOS):
  Windows:      start-gymos-server.cmd
  macOS/Linux:  ./start-gymos-server.sh
The first start downloads a private PostgreSQL and may take a minute.

Then:
  - On this computer open http://localhost:8082 and sign up.
    Verification codes are printed in the server window.
  - Phones and other computers on the same Wi-Fi: open
${ips.isEmpty ? '      http://<this computer\'s IP>:8082' : ips.map((ip) => '      http://$ip:8082').join('\n')}
    or install the GymOS APK from releases/ and tap "Change" next to
    "Server" on the sign-in screen to enter ${ips.isEmpty ? '<this computer\'s IP>:8080' : '${ips.first}:8080'}.
  - If your firewall asks, allow Dart on private networks.''');
}

String? _key(String name, String description, bool prompt) {
  final fromEnv = Platform.environment[name]?.trim();
  if (fromEnv != null && fromEnv.isNotEmpty) return _checked(name, fromEnv);
  if (!prompt) return null;
  stdout.write('  $description\n  Paste $name, or press Enter to skip: ');
  final hidden = stdin.hasTerminal;
  if (hidden) stdin.echoMode = false;
  final value = stdin.readLineSync()?.trim() ?? '';
  if (hidden) {
    stdin.echoMode = true;
    stdout.writeln(value.isEmpty ? '(skipped)' : '(saved)');
  }
  return value.isEmpty ? null : _checked(name, value);
}

String _checked(String name, String value) {
  if (!RegExp(r'^[A-Za-z0-9_\-.]+$').hasMatch(value)) {
    _fail('$name contains unexpected characters.');
  }
  return value;
}

String _passwordsYaml(String? groq, String? events) {
  final random = Random.secure();
  const chars =
      'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
  String secret() =>
      List.generate(32, (_) => chars[random.nextInt(chars.length)]).join();
  return '''
# Local secrets for this computer, generated by tool/setup.dart.
# Never commit this file. Add or change API keys under "development".
development:
  database: '${secret()}'
  serviceSecret: '${secret()}'
  emailSecretHashPepper: '${secret()}'
  jwtRefreshTokenHashPepper: '${secret()}'
${groq == null ? '  # GROQ_API_KEY: \'paste-your-groq-key\'' : "  GROQ_API_KEY: '$groq'"}
${events == null ? '  # ALLEVENTS_API_KEY: \'paste-your-parse-bot-key\'' : "  ALLEVENTS_API_KEY: '$events'"}
''';
}

Future<void> _run(String exe, List<String> args, Directory dir) async {
  stdout.writeln('  > $exe ${args.join(' ')}');
  final process = await Process.start(
    exe,
    args,
    workingDirectory: dir.path,
    runInShell: true,
    mode: ProcessStartMode.inheritStdio,
  );
  final code = await process.exitCode;
  if (code != 0) {
    _fail(
      '"$exe ${args.join(' ')}" failed (exit $code). Is Flutter installed '
      'and on your PATH? Check with "flutter doctor".',
    );
  }
}

void _copy(Directory from, Directory to) {
  to.createSync(recursive: true);
  for (final entity in from.listSync(recursive: true)) {
    final relative = entity.path.substring(from.path.length + 1);
    final destination = '${to.path}/$relative';
    if (entity is Directory) {
      Directory(destination).createSync(recursive: true);
    } else if (entity is File) {
      File(destination).parent.createSync(recursive: true);
      entity.copySync(destination);
    }
  }
}

Future<List<String>> _lanAddresses() async {
  try {
    return [
      for (final nic in await NetworkInterface.list(
        type: InternetAddressType.IPv4,
      ))
        for (final address in nic.addresses)
          if (!address.isLoopback &&
              (address.address.startsWith('192.168.') ||
                  address.address.startsWith('10.') ||
                  RegExp(r'^172\.(1[6-9]|2\d|3[01])\.')
                      .hasMatch(address.address)))
            address.address,
    ];
  } catch (_) {
    return [];
  }
}

String _rel(FileSystemEntity e) =>
    e.path.replaceFirst(_root.path, '').replaceAll('\\', '/');

void _step(String n, String title) => stdout.writeln('\n[$n] $title');

Never _fail(String message) {
  stderr.writeln('\nSetup failed: $message');
  exit(1);
}
